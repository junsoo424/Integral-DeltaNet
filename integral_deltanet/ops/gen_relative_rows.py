#!/usr/bin/env python3
"""Generate the row-explicit direct-relative C16 backward kernel.

The tile kernels hold the sixteen source rows of a chunk as one (C, BK)
tensor and advance it with masked whole-tile operations, so every step does
sixteen rows of work for the (on average) eight that are live, every
per-target reduction over sources is a cross-lane shuffle tree, and every
"only row t" update is a masked select over the whole tile.

Here the recurrence is unrolled over sources as well as targets: each source
row is its own (BK,) vector, every (source, target) pair is emitted exactly
once, reductions over sources are plain register adds, and rows that are not
live simply do not appear.  The sequence of floating-point operations per
value is otherwise the same as `_direct_c16_segment_bwd_reuse_kernel`.

Segment starts are checkpointed through a per-program scratch slice rather
than replayed, keeping no recurrence state live across segment boundaries.

Run this file to regenerate `general_direct_relative_rows_triton.py`.
"""
from __future__ import annotations

import argparse
from pathlib import Path

try:
    from .gen_merge import merge_kernels
except ImportError:                      # run as a script
    from gen_merge import merge_kernels

C = 16


def generate_header(segments: list[tuple[int, int]]) -> str:
    n_ckpt = len([a for a, _ in segments if a > 0])
    return (
        '"""Generated by gen_relative_rows.py -- do not edit by hand."""\n'
        "from __future__ import annotations\n\n"
        "import triton\n"
        "import triton.language as tl\n\n"
        f"ROWS_SEGMENTS = {segments!r}\n"
        f"ROWS_CHECKPOINTS = {n_ckpt}\n\n"
    )


def generate(segments: list[tuple[int, int]], suffix: str = "", fuse_prefix: bool = False, header: bool = True) -> str:
    assert segments[0][0] == 0 and segments[-1][1] == C
    for (a, b), (c, d) in zip(segments, segments[1:]):
        assert b == c
    starts = [a for a, _ in segments if a > 0]      # checkpointed segment starts
    n_ckpt = len(starts)
    out: list[str] = []
    ind = [0]

    def w(line: str = "") -> None:
        out.append(("    " * ind[0] + line) if line else "")

    if header:
        out.append(generate_header(segments))
    w("@triton.jit")
    name = "_direct_c16_fused_bwd_rows" if fuse_prefix else "_direct_c16_segment_bwd_rows"
    w(f"def {name}{suffix}_kernel(")
    w("    Q, K_IN, G, B_GATE, GAMMA, LAM,")
    w("    DMATRIX, DCAUSAL, DTAIL1, DTAIL2,")
    if fuse_prefix:
        w("    DA1, DA2, DQ1, DQ2, DTRANSPORT,")
    w("    DQ, DK, DG, DB, DGAMMA_PARTIAL, DLAM_PARTIAL,")
    w("    SCRATCH,")
    w("    T: tl.constexpr, H: tl.constexpr, N: tl.constexpr,")
    w("    K: tl.constexpr, C: tl.constexpr, NK: tl.constexpr,")
    w("    SCALE: tl.constexpr,")
    w("    SB0: tl.constexpr, SB1: tl.constexpr,")
    w("    SB2: tl.constexpr, SB3: tl.constexpr,")
    w("    BK: tl.constexpr,")
    w("):")
    ind[0] = 1
    w("key_block = tl.program_id(0) % NK")
    w("system = tl.program_id(0) // NK")
    w("chunk = system % N")
    w("head = (system // N) % H")
    w("batch = system // (N * H)")
    w("keys = key_block * BK + tl.arange(0, BK)")
    w("key_mask = keys < K")
    w("base = ((batch * T + chunk * C) * H + head) * K + keys")
    w("bbase = batch * SB0 + (chunk * C) * SB1 + head * SB2 + keys * SB3")
    w("sbase = (batch * T + chunk * C) * H + head")
    w("tbase = system * C * K + keys")
    w("mbase = system * C * C")
    w("pbase = (system * NK + key_block) * C")
    slot_vectors = 2 * C + (4 if fuse_prefix else 0)
    w("scratch = SCRATCH + tl.program_id(0).to(tl.int64) * (%d * BK) + tl.arange(0, BK)" % (max(n_ckpt, 1) * slot_vectors))
    w("trbase = (system * K + keys) * 4")
    w("one = tl.full((BK,), 1.0, tl.float32)")
    w("zero = tl.zeros((BK,), tl.float32)")
    w()
    # per-row loads
    for s in range(C):
        w(f"k_{s} = tl.load(K_IN + base + {s} * H * K, mask=key_mask, other=0.0).to(tl.float32)")
    for s in range(C):
        w(f"lam_{s} = tl.load(LAM + sbase + {s} * H).to(tl.float32)")
    for s in range(C):
        w(f"dc1_{s} = tl.load(DTAIL1 + tbase + {s} * K, mask=key_mask, other=0.0).to(tl.float32) * k_{s}")
        w(f"dc2_{s} = tl.load(DTAIL2 + tbase + {s} * K, mask=key_mask, other=0.0).to(tl.float32) * k_{s}")
    w()

    def emit_transition(t: int) -> None:
        w(f"alpha_{t} = tl.exp(tl.load(G + base + {t} * H * K, mask=key_mask, other=0.0).to(tl.float32))")
        w(f"gamma_{t} = tl.load(GAMMA + sbase + {t} * H).to(tl.float32)")
        w(f"p11_{t} = gamma_{t} * alpha_{t}")
        w(f"p12_{t} = lam_{t} * p11_{t}")
        w(f"p21_{t} = (1.0 - gamma_{t}) * alpha_{t}")
        w(f"p22_{t} = (1.0 - lam_{t}) + lam_{t} * p21_{t}")

    def emit_step(src1: str, src2: str, dst1: str, dst2: str, t: int, rows: int) -> None:
        """dst(s) = src(s) @ P_t for s < rows; rows >= t keep the initial value."""
        for s in range(rows):
            if s < t:
                w(f"{dst1}_{s} = {src1}_{s} * p11_{t} + {src2}_{s} * p21_{t}")
                w(f"{dst2}_{s} = {src1}_{s} * p12_{t} + {src2}_{s} * p22_{t}")
            else:
                w(f"{dst1}_{s} = {src1}_{s}")
                w(f"{dst2}_{s} = {src2}_{s}")

    # ---- forward sweep with checkpoints -------------------------------------
    w("# forward sweep: c(s) = e_s P_{s+1} ... P_t, checkpointing segment starts")
    for s in range(C):
        w(f"c1_{s} = one")
        w(f"c2_{s} = lam_{s} + zero")
    if fuse_prefix:
        w("f11 = one")
        w("f12 = zero")
        w("f21 = zero")
        w("f22 = one")
    for t in range(C):
        if t in starts:
            slot = starts.index(t)
            w(f"# checkpoint: start of segment {t}")
            for s in range(t):
                w(f"tl.store(scratch + ({slot} * {slot_vectors} + {s}) * BK, c1_{s})")
                w(f"tl.store(scratch + ({slot} * {slot_vectors} + C + {s}) * BK, c2_{s})")
            if fuse_prefix:
                for i, nm in enumerate(("f11", "f12", "f21", "f22")):
                    w(f"tl.store(scratch + ({slot} * {slot_vectors} + 2 * C + {i}) * BK, {nm})")
        emit_transition(t)
        for s in range(t):
            w(f"c1_{s}, c2_{s} = c1_{s} * p11_{t} + c2_{s} * p21_{t}, c1_{s} * p12_{t} + c2_{s} * p22_{t}")
        if fuse_prefix:
            w(f"f11, f12, f21, f22 = f11 * p11_{t} + f12 * p21_{t}, f11 * p12_{t} + f12 * p22_{t}, f21 * p11_{t} + f22 * p21_{t}, f21 * p12_{t} + f22 * p22_{t}")
    if fuse_prefix:
        w("# prefix adjoint starts from the transport gradient")
        for i, nm in enumerate(("df11", "df12", "df21", "df22")):
            w(f"{nm} = tl.load(DTRANSPORT + trbase + {i}, mask=key_mask, other=0.0).to(tl.float32)")
    w("# tail adjoint and the carry (state after the newest target)")
    for s in range(C):
        w(f"dk_{s} = tl.load(DTAIL1 + tbase + {s} * K, mask=key_mask, other=0.0).to(tl.float32) * c1_{s} "
          f"+ tl.load(DTAIL2 + tbase + {s} * K, mask=key_mask, other=0.0).to(tl.float32) * c2_{s}")
    for s in range(C):
        w(f"ca_{s} = c1_{s}")
    w()

    # ---- reverse segments ----------------------------------------------------
    for seg_idx, (a, b) in reversed(list(enumerate(segments))):
        L = b - a
        w(f"# ---- segment [{a}, {b}) ----")
        if a > 0:
            slot = starts.index(a)
            for s in range(a):
                w(f"h0a_{s} = tl.load(scratch + ({slot} * {slot_vectors} + {s}) * BK)")
                w(f"h0b_{s} = tl.load(scratch + ({slot} * {slot_vectors} + C + {s}) * BK)")
            if fuse_prefix:
                for i, nm in enumerate(("f11", "f12", "f21", "f22")):
                    w(f"g0{nm} = tl.load(scratch + ({slot} * {slot_vectors} + 2 * C + {i}) * BK)")
        elif fuse_prefix:
            w("g0f11 = one")
            w("g0f12 = zero")
            w("g0f21 = zero")
            w("g0f22 = one")
        # rows a..b-1 of h0 are initial (e_s) -- their values are used as cprev(s, t) for t <= s? No:
        # cprev(s, t) is only needed for s < t.  h_j holds rows s < a + j.  Row a+j-1 of h_j is e_s.
        for j in range(1, L):
            t = a + j - 1
            for s in range(a + j):
                if s < t:
                    w(f"h{j}a_{s} = h{j-1}a_{s} * p11_{t} + h{j-1}b_{s} * p21_{t}")
                    w(f"h{j}b_{s} = h{j-1}a_{s} * p12_{t} + h{j-1}b_{s} * p22_{t}")
                elif s == t:
                    w(f"h{j}a_{s} = one")
                    w(f"h{j}b_{s} = lam_{s} + zero")
        # prefix states inside the segment are rebuilt per target from g0
        # (at most L-1 cheap 2x2 steps) rather than kept live: the extra live
        # vectors would cost more than the arithmetic.
        for j in reversed(range(L)):
            t = a + j
            hp = f"h{j}"   # cprev(s, t) for s < t
            # cafter(s, t) for s < t: h{j+1}a for j+1 < L, else carry
            hn = f"h{j+1}a" if j + 1 < L else "ca"
            w(f"# target {t}")
            w(f"q_{t} = tl.load(Q + base + {t} * H * K, mask=key_mask, other=0.0).to(tl.float32) * SCALE")
            w(f"kt_{t} = tl.load(K_IN + base + {t} * H * K, mask=key_mask, other=0.0).to(tl.float32)")
            w(f"b_{t} = tl.load(B_GATE + bbase + {t} * SB1, mask=key_mask, other=0.0).to(tl.float32)")
            w(f"erase_{t} = alpha_{t} * b_{t} * kt_{t}")
            w(f"diag_{t} = tl.load(DCAUSAL + mbase + {t} * C + {t}).to(tl.float32)")
            w(f"dq_{t} = zero")
            w(f"dp11_{t} = zero")
            w(f"dp12_{t} = zero")
            w(f"dp21_{t} = zero")
            w(f"dp22_{t} = zero")
            w(f"derase_{t} = zero")
            for s in range(t):
                w(f"dm = tl.load(DMATRIX + mbase + {t} * C + {s}).to(tl.float32)")
                w(f"dl = tl.load(DCAUSAL + mbase + {t} * C + {s}).to(tl.float32)")
                w(f"after1 = dc1_{s} + dl * k_{s} * q_{t}")
                w(f"cwca = dl * {hn}_{s}")
                w(f"dq_{t} += cwca * k_{s}")
                w(f"dk_{s} += cwca * q_{t}")
                w(f"dp11_{t} += {hp}a_{s} * after1")
                w(f"dp12_{t} += {hp}a_{s} * dc2_{s}")
                w(f"dp21_{t} += {hp}b_{s} * after1")
                w(f"dp22_{t} += {hp}b_{s} * dc2_{s}")
                w(f"mwcp = dm * {hp}a_{s}")
                w(f"dk_{s} += mwcp * erase_{t}")
                w(f"derase_{t} += mwcp * k_{s}")
                w(f"prev1 = after1 * p11_{t} + dc2_{s} * p12_{t} + dm * k_{s} * erase_{t}")
                w(f"dc2_{s} = after1 * p21_{t} + dc2_{s} * p22_{t}")
                w(f"dc1_{s} = prev1")
            w(f"dq_{t} = dq_{t} + diag_{t} * kt_{t}")
            w(f"dq_{t} = dq_{t} * SCALE")
            if fuse_prefix:
                gp = "gc"
                w(f"# prefix backward, token {t}: rebuild the prefix before token {t} from g0")
                w("gcf11, gcf12, gcf21, gcf22 = g0f11, g0f12, g0f21, g0f22")
                for tt in range(a, t):
                    w(f"gcf11, gcf12, gcf21, gcf22 = gcf11 * p11_{tt} + gcf12 * p21_{tt}, gcf11 * p12_{tt} + gcf12 * p22_{tt}, gcf21 * p11_{tt} + gcf22 * p21_{tt}, gcf21 * p12_{tt} + gcf22 * p22_{tt}")
                w(f"n11 = {gp}f11 * p11_{t} + {gp}f12 * p21_{t}")
                w(f"n21 = {gp}f21 * p11_{t} + {gp}f22 * p21_{t}")
                w(f"pa1 = tl.load(DA1 + tbase + {t} * K, mask=key_mask, other=0.0).to(tl.float32)")
                w(f"pa2 = tl.load(DA2 + tbase + {t} * K, mask=key_mask, other=0.0).to(tl.float32)")
                w(f"pq1 = tl.load(DQ1 + tbase + {t} * K, mask=key_mask, other=0.0).to(tl.float32)")
                w(f"pq2 = tl.load(DQ2 + tbase + {t} * K, mask=key_mask, other=0.0).to(tl.float32)")
                w(f"dn11 = df11 + pq1 * q_{t}")
                w(f"dn21 = df21 + pq2 * q_{t}")
                w(f"dq_{t} += (pq1 * n11 + pq2 * n21) * SCALE")
                w(f"xp11 = {gp}f11 * dn11 + {gp}f21 * dn21")
                w(f"xp12 = {gp}f11 * df12 + {gp}f21 * df22")
                w(f"xp21 = {gp}f12 * dn11 + {gp}f22 * dn21")
                w(f"xp22 = {gp}f12 * df12 + {gp}f22 * df22")
                w(f"pderase = pa1 * {gp}f11 + pa2 * {gp}f21")
                w(f"nf11 = dn11 * p11_{t} + df12 * p12_{t} + pa1 * erase_{t}")
                w(f"nf12 = dn11 * p21_{t} + df12 * p22_{t}")
                w(f"nf21 = dn21 * p11_{t} + df22 * p12_{t} + pa2 * erase_{t}")
                w(f"nf22 = dn21 * p21_{t} + df22 * p22_{t}")
                w(f"df11, df12, df21, df22 = nf11, nf12, nf21, nf22")
                w(f"dp11_{t} += xp11")
                w(f"dp12_{t} += xp12")
                w(f"dp21_{t} += xp21")
                w(f"dp22_{t} += xp22")
                w(f"derase_{t} += pderase")
            w(f"dactive = dp11_{t} + lam_{t} * dp12_{t}")
            w(f"dpassive = dp21_{t} + lam_{t} * dp22_{t}")
            w(f"dalpha = gamma_{t} * dactive + (1.0 - gamma_{t}) * dpassive")
            w(f"dgamma_t = alpha_{t} * (dactive - dpassive)")
            w(f"dlam_{t} = p11_{t} * dp12_{t} + (p21_{t} - 1.0) * dp22_{t}")
            w(f"dalpha += derase_{t} * b_{t} * kt_{t}")
            w(f"db_t = derase_{t} * alpha_{t} * kt_{t}")
            w(f"dk_{t} += derase_{t} * alpha_{t} * b_{t} + diag_{t} * q_{t}")
            w(f"dg_t = dalpha * alpha_{t}")
            w(f"tl.store(DQ + base + {t} * H * K, dq_{t}, mask=key_mask)")
            w(f"tl.store(DG + base + {t} * H * K, dg_t, mask=key_mask)")
            w(f"tl.store(DB + base + {t} * H * K, db_t, mask=key_mask)")
            w(f"tl.store(DGAMMA_PARTIAL + pbase + {t}, tl.sum(tl.where(key_mask, dgamma_t, 0.0), axis=0))")
        # carry for the next (lower) segment: cafter(s, a-1) = cprev(s, a) = h0 rows
        if a > 0:
            for s in range(a):
                w(f"ca_{s} = h0a_{s}")
        w()
    w("# epilogue")
    for s in range(C):
        w(f"tl.store(DK + base + {s} * H * K, dk_{s}, mask=key_mask)")
    for s in range(C):
        w(f"tl.store(DLAM_PARTIAL + pbase + {s}, tl.sum(tl.where(key_mask, dlam_{s} + dc2_{s}, 0.0), axis=0))")
    return "\n".join(out) + "\n"


def generate_forward(fuse_prefix: bool = False) -> str:
    """Row-explicit direct-relative C16 forward, one program per (system, key block).

    Emits the same per-value arithmetic as `_direct_c16_group_fwd_kernel`, but
    unrolled over targets and sources so every load is hoistable and no masked
    tile work exists.  MATRIX / CAUSAL reductions over keys are partial per key
    block and summed by `_rows_fwd_reduce_kernel`.
    """
    out: list[str] = []
    ind = [0]

    def w(line: str = "") -> None:
        out.append(("    " * ind[0] + line) if line else "")

    w("@triton.jit")
    name = "_direct_c16_fused_fwd_rows" if fuse_prefix else "_direct_c16_group_fwd_rows"
    w(f"def {name}_kernel(")
    w("    Q, K_IN, G, B_GATE, GAMMA, LAM,")
    if fuse_prefix:
        w("    A1, A2, Q1, Q2, TRANSPORT,")
    w("    TAIL1, TAIL2, MPART, CPART,")
    w("    T: tl.constexpr, H: tl.constexpr, N: tl.constexpr,")
    w("    K: tl.constexpr, C: tl.constexpr, NK: tl.constexpr,")
    w("    SCALE: tl.constexpr,")
    w("    SB0: tl.constexpr, SB1: tl.constexpr,")
    w("    SB2: tl.constexpr, SB3: tl.constexpr,")
    w("    BK: tl.constexpr,")
    w("):")
    ind[0] = 1
    w("key_block = tl.program_id(0) % NK")
    w("system = tl.program_id(0) // NK")
    w("chunk = system % N")
    w("head = (system // N) % H")
    w("batch = system // (N * H)")
    w("keys = key_block * BK + tl.arange(0, BK)")
    w("key_mask = keys < K")
    w("base = ((batch * T + chunk * C) * H + head) * K + keys")
    w("bbase = batch * SB0 + (chunk * C) * SB1 + head * SB2 + keys * SB3")
    w("sbase = (batch * T + chunk * C) * H + head")
    w("tbase = system * C * K + keys")
    w("pbase = (system * NK + key_block) * C * C")
    w("one = tl.full((BK,), 1.0, tl.float32)")
    w("zero = tl.zeros((BK,), tl.float32)")
    for s in range(C):
        w(f"k_{s} = tl.load(K_IN + base + {s} * H * K, mask=key_mask, other=0.0).to(tl.float32)")
    for s in range(C):
        w(f"lam_{s} = tl.load(LAM + sbase + {s} * H).to(tl.float32)")
    for s in range(C):
        w(f"c1_{s} = one")
        w(f"c2_{s} = lam_{s} + zero")
    if fuse_prefix:
        w("f11 = one")
        w("f12 = zero")
        w("f21 = zero")
        w("f22 = one")
    for t in range(C):
        w(f"# target {t}")
        w(f"q_{t} = tl.load(Q + base + {t} * H * K, mask=key_mask, other=0.0).to(tl.float32) * SCALE")
        w(f"g_{t} = tl.load(G + base + {t} * H * K, mask=key_mask, other=0.0).to(tl.float32)")
        w(f"b_{t} = tl.load(B_GATE + bbase + {t} * SB1, mask=key_mask, other=0.0).to(tl.float32)")
        w(f"alpha_{t} = tl.exp(g_{t})")
        w(f"erase_{t} = alpha_{t} * b_{t} * k_{t}")
        w(f"gamma_{t} = tl.load(GAMMA + sbase + {t} * H).to(tl.float32)")
        w(f"p11_{t} = gamma_{t} * alpha_{t}")
        w(f"p12_{t} = lam_{t} * p11_{t}")
        w(f"p21_{t} = (1.0 - gamma_{t}) * alpha_{t}")
        w(f"p22_{t} = (1.0 - lam_{t}) + lam_{t} * p21_{t}")
        for s in range(t):
            w(f"tl.store(MPART + pbase + {t} * C + {s}, tl.sum(tl.where(key_mask, c1_{s} * k_{s} * erase_{t}, 0.0), axis=0))")
        if fuse_prefix:
            w(f"tl.store(A1 + tbase + {t} * K, f11 * erase_{t}, mask=key_mask)")
            w(f"tl.store(A2 + tbase + {t} * K, f21 * erase_{t}, mask=key_mask)")
        for s in range(t):
            w(f"c1_{s}, c2_{s} = c1_{s} * p11_{t} + c2_{s} * p21_{t}, c1_{s} * p12_{t} + c2_{s} * p22_{t}")
        if fuse_prefix:
            w(f"f11, f12, f21, f22 = f11 * p11_{t} + f12 * p21_{t}, f11 * p12_{t} + f12 * p22_{t}, f21 * p11_{t} + f22 * p21_{t}, f21 * p12_{t} + f22 * p22_{t}")
            w(f"tl.store(Q1 + tbase + {t} * K, f11 * q_{t}, mask=key_mask)")
            w(f"tl.store(Q2 + tbase + {t} * K, f21 * q_{t}, mask=key_mask)")
        for s in range(t + 1):
            w(f"tl.store(CPART + pbase + {t} * C + {s}, tl.sum(tl.where(key_mask, c1_{s} * k_{s} * q_{t}, 0.0), axis=0))")
    if fuse_prefix:
        w("trbase = (system * K + keys) * 4")
        for i, nm in enumerate(("f11", "f12", "f21", "f22")):
            w(f"tl.store(TRANSPORT + trbase + {i}, {nm}, mask=key_mask)")
    w("# tails")
    for s in range(C):
        w(f"tl.store(TAIL1 + tbase + {s} * K, c1_{s} * k_{s}, mask=key_mask)")
        w(f"tl.store(TAIL2 + tbase + {s} * K, c2_{s} * k_{s}, mask=key_mask)")
    return "\n".join(out) + "\n"


def generate_reduce() -> str:
    """Sum the per-key-block MATRIX / CAUSAL partials of the row forward."""
    out: list[str] = []
    ind = [0]

    def w(line: str = "") -> None:
        out.append(("    " * ind[0] + line) if line else "")

    w("@triton.jit")
    w("def _rows_fwd_reduce_kernel(")
    w("    MPART, CPART, MATRIX, CAUSAL,")
    w("    C: tl.constexpr, NK: tl.constexpr, BLOCK_NK: tl.constexpr,")
    w("):")
    ind[0] = 1
    w("system = tl.program_id(0)")
    w("cells = tl.arange(0, C * C)")
    w("blocks = tl.arange(0, BLOCK_NK)")
    w("offsets = (system * NK + blocks[:, None]) * C * C + cells[None, :]")
    w("mask = (blocks < NK)[:, None]")
    w("# strict lower (target > source) for MATRIX, lower-inclusive for CAUSAL")
    w("target = cells // C")
    w("source = cells % C")
    w("m = tl.sum(tl.load(MPART + offsets, mask=mask, other=0.0), axis=0)")
    w("c = tl.sum(tl.load(CPART + offsets, mask=mask, other=0.0), axis=0)")
    w("tl.store(MATRIX + system * C * C + cells, tl.where(source < target, m, 0.0))")
    w("tl.store(CAUSAL + system * C * C + cells, tl.where(source <= target, c, 0.0).to(CAUSAL.dtype.element_ty))")
    return "\n".join(out) + "\n"


BACKWARD_COMMENT = """\
Row-explicit direct-relative C16 backward.  FUSED_PREFIX: the prefix
recurrence (the A1/A2/Q1/Q2 operands and the chunk transport) is fused in and
its gradients folded into the same partial sums; otherwise the prefix runs in
its own kernels and DA1..DTRANSPORT are None.  ops/arch.py picks the flag."""

FORWARD_COMMENT = """\
Row-explicit direct-relative C16 forward; MATRIX / CAUSAL partials per key
block, summed by _rows_fwd_reduce_kernel.  FUSED_PREFIX: also writes the
prefix operands A1/A2/Q1/Q2 and the chunk transport; otherwise they are None."""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--segments", default="0,10,13,15,16",
                    help="comma-separated segment boundaries (must start at 0 and end at 16)")
    ap.add_argument("--out", default=str(Path(__file__).with_name("general_direct_relative_rows_triton.py")))
    args = ap.parse_args()
    bounds = [int(x) for x in args.segments.split(",")]
    segments = list(zip(bounds, bounds[1:]))
    fused = {"FUSED_PREFIX": True}
    split = {"FUSED_PREFIX": False}
    backward = merge_kernels(
        "_direct_c16_bwd_rows_kernel",
        {"fused": generate(segments, fuse_prefix=True, header=False),
         "split": generate(segments, header=False)},
        {"fused": fused, "split": split},
        BACKWARD_COMMENT,
    )
    forward = merge_kernels(
        "_direct_c16_fwd_rows_kernel",
        {"fused": generate_forward(fuse_prefix=True), "split": generate_forward()},
        {"fused": fused, "split": split},
        FORWARD_COMMENT,
    )
    Path(args.out).write_text(
        generate_header(segments) + "\n" + backward + "\n\n" + forward + "\n\n" + generate_reduce()
    )
    print(f"wrote {args.out} ({len(segments)} segments, {len(segments) - 1} checkpoints)")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate the row-explicit readout-side C16 builder kernels.

The tile kernels in :mod:`readout_triton` hold the sixteen source rows of a
chunk as one ``(BK, C)`` register tile and pay, per target row, for a full
tile pass whenever a single row is needed (``where`` + reduction) and for a
broadcast whenever a per-row vector meets the tile.  Here every row is its
own ``(BK,)`` vector and every (target, source) pair is emitted exactly once
as straight-line code, so there are no extractions, no broadcasts, one
element per thread at every block size, and additional warps split the key
axis (the only axis there is) instead of the rows.

Forward (per program = one chunk x one key block), all vectors over keys::

    G_i = G_{i-1} + g_i,  A_i = exp(G_i)
    e_ij = exp(G_i - G_j)                       (j < i; e_ii = 1)
    P_j <- (1 - lam_i) P_j + lam_i e_ij  (j < i),  P_i = lam_i
    Bnd <- (1 - lam_i) Bnd + lam_i A_i,  keep <- keep (1 - lam_i)
    interaction[i, j] = <b_i k_i, k_j e_ij>     (j < i)
    causal[i, j]      = <k_j, gamma_i q_i e_ij + (1 - gamma_i) q_i P_j>
    abar_i = A_i b_i k_i,  q1_i = gamma_i q_i A_i + (1 - gamma_i) q_i Bnd,
    q2_i = (1 - gamma_i) q_i keep;  tail1_j = k_j e_{end,j}, tail2_j = k_j P_j,
    transport = (A_end, Bnd_end, 0, keep_end)

Backward: a forward pre-pass checkpoints ``P``, ``Bnd`` at rows 3, 7, 11
(``CP = 4``), then a reverse sweep over the target rows runs the adjoint
recurrences ``QP_j <- dP_j + (1 - lam_{i+1}) QP_j`` (``dE_ij += lam_i QP_j``),
``QB``, ``ql`` likewise, and ``dlam_i = <QP, e_i - P^{(i-1)}> + <QB, A_i -
Bnd^{(i-1)}> - keep^{(i-1)} ql`` with ``P^{(i-1)}`` rebuilt from the nearest
checkpoint (at most ``CP - 1`` steps).  Every exponential is relative and
every ``lambda`` factor is in ``[0, 1]``.  Because the sweep is reverse, the
column part of the decay cotangent for row ``i`` is complete when row ``i``
is reached, so ``dg_s = sum_{i >= s} dG_i`` is accumulated on the fly.

Run ``python -m integral_deltanet.ops.gen_readout_rows`` to regenerate
``readout_rows_triton.py``.
"""
from __future__ import annotations

import argparse
from pathlib import Path

try:
    from .gen_merge import merge_kernels
except ImportError:                      # run as a script
    from gen_merge import merge_kernels

C = 16


def checkpoints(cp: int) -> list[int]:
    return [cp * s - 1 for s in range(1, C // cp)]      # cp=4: rows 3, 7, 11

HEADER = '''"""Generated by gen_readout_rows.py -- do not edit by hand."""
from __future__ import annotations

import triton
import triton.language as tl

'''


class Emitter:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.indent = 1

    def __call__(self, line: str = "") -> None:
        self.lines.append(("    " * self.indent + line) if line else "")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def _prologue(w: Emitter, name: str, extra_ptrs: str, scratch: bool = False, product: bool = False) -> None:
    w.indent = 0
    w("@triton.jit")
    w(f"def {name}(")
    w.indent = 1
    w("Q, K_IN, G, B_GATE, GAMMA, LAM,")
    w(extra_ptrs)
    w("T: tl.constexpr, H: tl.constexpr, N: tl.constexpr,")
    w("K: tl.constexpr, C: tl.constexpr, NK: tl.constexpr,")
    w("SCALE: tl.constexpr,")
    w("SB0: tl.constexpr, SB1: tl.constexpr, SB2: tl.constexpr, SB3: tl.constexpr,")
    w("SG0: tl.constexpr, SG1: tl.constexpr, SG2: tl.constexpr, SG3: tl.constexpr,")
    w("SL0: tl.constexpr, SL1: tl.constexpr, SL2: tl.constexpr, SL3: tl.constexpr,")
    w("SD0: tl.constexpr, SD1: tl.constexpr, SD2: tl.constexpr, SD3: tl.constexpr,")
    w("BK: tl.constexpr,")
    w.indent = 0
    w("):")
    w.indent = 1
    if scratch:
        w("scratch = SCRATCH + tl.program_id(0).to(tl.int64) * (SLOTS * BK) + tl.arange(0, BK)")
    w("key_block = tl.program_id(0) % NK")
    w("system = tl.program_id(0) // NK")
    w("chunk = system % N")
    w("head = (system // N) % H")
    w("batch = system // (N * H)")
    w("keys = key_block * BK + tl.arange(0, BK)")
    w("key_mask = keys < K")
    w("base = ((batch * T + chunk * C) * H + head) * K + keys")
    w("bbase = batch * SB0 + (chunk * C) * SB1 + head * SB2 + keys * SB3")
    w("gbase = batch * SG0 + (chunk * C) * SG1 + head * SG2 + keys * SG3")
    w("lbase = batch * SL0 + (chunk * C) * SL1 + head * SL2 + keys * SL3")
    w("dbase = batch * SD0 + (chunk * C) * SD1 + head * SD2 + keys * SD3")
    w("sbase = (batch * T + chunk * C) * H + head")
    w("vbase = system * C * K + keys")
    w("qbase = system * C * C")
    w("pbase = (system * NK + key_block) * C * C")
    w("zero = tl.zeros((BK,), tl.float32)")
    for j in range(C):
        w(f"k_{j} = tl.load(K_IN + base + {j} * H * K, mask=key_mask, other=0.0).to(tl.float32)")
    if not product:
        for j in range(C):
            w(f"lam_{j} = tl.load(LAM + lbase + {j} * SL1, mask=key_mask, other=0.0).to(tl.float32)")
        for j in range(C):
            g = f"tl.load(G + dbase + {j} * SD1, mask=key_mask, other=0.0).to(tl.float32)"
            w(f"G_{j} = {g}" if j == 0 else f"G_{j} = G_{j - 1} + {g}")


def _row_loads(w: Emitter, i: int) -> None:
    w(f"q_i = tl.load(Q + base + {i} * H * K, mask=key_mask, other=0.0).to(tl.float32) * SCALE")
    w(f"b_i = tl.load(B_GATE + bbase + {i} * SB1, mask=key_mask, other=0.0).to(tl.float32)")
    w(f"gm_i = tl.load(GAMMA + gbase + {i} * SG1, mask=key_mask, other=0.0).to(tl.float32)")
    w("qa = gm_i * q_i")
    w("qs = q_i - qa")
    w(f"er = b_i * k_{i}")


def _relative(w: Emitter, i: int, prefix: str = "e") -> None:
    for j in range(i):
        w(f"{prefix}_{j} = tl.exp(tl.minimum(G_{i} - G_{j}, 0.0))")


def _alpha(t: int, reload: bool) -> str:
    """The decay factor of row ``t``; reloaded (volatile) to keep a rebuild's
    product chain private to its target row."""
    if not reload:
        return f"alpha_{t}"
    return f"tl.exp(tl.load(G + dbase + {t} * SD1, mask=key_mask, other=0.0, volatile=True).to(tl.float32))"


def generate_forward(product: bool = True) -> str:
    w = Emitter()
    name = "_readout_rows_fwd_kernel" if product else "_readout_rows_fwd_exp_kernel"
    _prologue(w, name,
              "ABAR, QBAR1, QBAR2, TAIL1, TAIL2, TRANSPORT, MPART, CPART,", product=product)
    w("keep = zero + 1.0")
    w("bnd = zero")
    for i in range(C):
        w(f"# ---- target row {i} ----")
        _row_loads(w, i)
        if product:
            w(f"lam_{i} = tl.load(LAM + lbase + {i} * SL1, mask=key_mask, other=0.0).to(tl.float32)")
            w(f"alpha = tl.exp(tl.load(G + dbase + {i} * SD1, mask=key_mask, other=0.0).to(tl.float32))")
            w("a_i = alpha" if i == 0 else "a_i = a_i * alpha")
        else:
            w(f"a_i = tl.exp(G_{i})")
        w(f"retain = 1.0 - lam_{i}")
        w("keep = keep * retain")
        w(f"bnd = retain * bnd + lam_{i} * a_i")
        if product:
            # E[i,j] = alpha_i E[i-1,j]. All factors are in [0,1]: no
            # inverse decay, 16 exponentials instead of 136, fewer live prefixes.
            for j in range(i):
                w(f"e_{j} = alpha" if j == i - 1 else f"e_{j} = alpha * e_{j}")
        else:
            _relative(w, i)
        for j in range(i):
            w(f"p_{j} = retain * p_{j} + lam_{i} * e_{j}")
        w(f"p_{i} = zero + lam_{i}")
        for j in range(i):
            w(f"tl.store(MPART + pbase + {i * C + j}, tl.sum(er * k_{j} * e_{j}, axis=0))")
        for j in range(i):
            w(f"tl.store(CPART + pbase + {i * C + j}, tl.sum(k_{j} * (qa * e_{j} + qs * p_{j}), axis=0))")
        w(f"tl.store(CPART + pbase + {i * C + i}, tl.sum(k_{i} * (qa + qs * p_{i}), axis=0))")
        w(f"tl.store(ABAR + vbase + {i} * K, (a_i * er).to(ABAR.dtype.element_ty), mask=key_mask)")
        w(f"tl.store(QBAR1 + vbase + {i} * K, (qa * a_i + qs * bnd).to(QBAR1.dtype.element_ty), mask=key_mask)")
        w(f"tl.store(QBAR2 + vbase + {i} * K, (qs * keep).to(QBAR2.dtype.element_ty), mask=key_mask)")
    w("# ---- tails and chunk transport ----")
    last = C - 1
    for j in range(C):
        t1 = f"k_{j} * e_{j}" if j < last else f"k_{j}"
        w(f"tl.store(TAIL1 + vbase + {j} * K, ({t1}).to(TAIL1.dtype.element_ty), mask=key_mask)")
        w(f"tl.store(TAIL2 + vbase + {j} * K, (k_{j} * p_{j}).to(TAIL2.dtype.element_ty), mask=key_mask)")
    w("transport = (system * K + keys) * 4")
    w("tl.store(TRANSPORT + transport + 0, a_i, mask=key_mask)")
    w("tl.store(TRANSPORT + transport + 1, bnd, mask=key_mask)")
    w("tl.store(TRANSPORT + transport + 2, zero, mask=key_mask)")
    w("tl.store(TRANSPORT + transport + 3, keep, mask=key_mask)")
    return w.text()


def generate_backward(cp: int = 4, scratch: bool = False, suffix: str = "",
                      reload_checkpoints: bool = False, product: bool = False) -> str:
    """Backward kernel; ``cp`` rows between checkpoints, optionally kept in a
    per-program global scratch slice instead of registers.

    ``product`` builds every decay as the forward kernel does, as a running
    product of the per-step factors ``alpha_t = exp(g_t)`` in ``[0, 1]``
    (``e_ij = alpha_i e_{i-1,j}``, ``A_i = alpha_i A_{i-1}``): 16 exponentials
    in the pre-pass instead of 152, and at most ``CP + 1`` per target row
    instead of one per (row, column) pair of every rebuild step.  With
    ``reload_checkpoints`` the rebuild factors are reloaded per row so the
    chains are not shared across rows."""
    CP = cp
    CHECKPOINTS = checkpoints(cp)
    slots = sum(c + 2 for c in CHECKPOINTS)              # P_0..P_c and Bnd per checkpoint
    w = Emitter()
    _prologue(w, f"_readout_rows_bwd_kernel{suffix}",
              "DABAR, DQBAR1, DQBAR2, DTAIL1, DTAIL2, DTRANSPORT, DMATRIX, DCAUSAL,\n"
              "    DQ, DK, DG, DB, DGAMMA, DLAM," + (" SCRATCH, SLOTS: tl.constexpr," if scratch else ""),
              scratch=scratch, product=product)
    if product:
        for j in range(C):
            w(f"lam_{j} = tl.load(LAM + lbase + {j} * SL1, mask=key_mask, other=0.0).to(tl.float32)")
        for j in range(C):
            w(f"alpha_{j} = tl.exp(tl.load(G + dbase + {j} * SD1, mask=key_mask, other=0.0).to(tl.float32))")
    slot_of = {}
    offset = 0
    for c in CHECKPOINTS:
        slot_of[c] = offset
        offset += c + 2
    assert offset == slots
    last = C - 1
    # ---- pre-pass: retention scalars, P / Bnd checkpoints ----------------
    w("# ---- forward pre-pass: keep_i, checkpoints of P and Bnd at rows "
      + ", ".join(str(c) for c in CHECKPOINTS) + " ----")
    w("bnd = zero")
    for i in range(C):
        w(f"retain = 1.0 - lam_{i}")
        w(f"keep_{i} = {'retain' if i == 0 else f'keep_{i - 1} * retain'}")
        if product:
            w("a = alpha_0" if i == 0 else f"a = a * alpha_{i}")
            w(f"bnd = retain * bnd + lam_{i} * a")
            for j in range(i):
                w(f"e_{j} = alpha_{i}" if j == i - 1 else f"e_{j} = alpha_{i} * e_{j}")
        else:
            w(f"bnd = retain * bnd + lam_{i} * tl.exp(G_{i})")
            _relative(w, i)
        for j in range(i):
            w(f"p_{j} = retain * p_{j} + lam_{i} * e_{j}")
        w(f"p_{i} = zero + lam_{i}")
        if i in CHECKPOINTS:
            for j in range(i + 1):
                if scratch:
                    w(f"tl.store(scratch + {slot_of[i] + j} * BK, p_{j})")
                else:
                    w(f"cp{i}_{j} = p_{j}")
            if scratch:
                w(f"tl.store(scratch + {slot_of[i] + i + 1} * BK, bnd)")
            else:
                w(f"bnd{i} = bnd")
    # ---- reverse sweep --------------------------------------------------
    w("# ---- reverse sweep over target rows ----")
    for j in range(C):
        w(f"dk_{j} = zero")
        w(f"dgc_{j} = zero")
    w("suffix = zero")
    w("QB = zero")
    w("ql = 0.0")
    for i in range(last, -1, -1):
        w(f"# ---- target row {i} ----")
        _row_loads(w, i)
        if not product:
            w(f"a_i = tl.exp(G_{i})")
        w(f"retain = 1.0 - lam_{i}")
        w(f"dabar_i = tl.load(DABAR + vbase + {i} * K, mask=key_mask, other=0.0).to(tl.float32)")
        w(f"dq1_i = tl.load(DQBAR1 + vbase + {i} * K, mask=key_mask, other=0.0).to(tl.float32)")
        w(f"dq2_i = tl.load(DQBAR2 + vbase + {i} * K, mask=key_mask, other=0.0).to(tl.float32)")
        for j in range(i + 1):
            w(f"dc_{j} = tl.load(DCAUSAL + qbase + {i * C + j}).to(tl.float32)")
        for j in range(i):
            w(f"dm_{j} = tl.load(DMATRIX + qbase + {i * C + j}).to(tl.float32)")
        # P^{(i-1)}, Bnd^{(i-1)} from the nearest checkpoint
        ap = None                                   # A of the latest rebuilt row (None: 1)
        if i == 0:
            w("bndp = zero")
            keep_prev = "1.0"
        else:
            seg_start = (i // CP) * CP
            cp = seg_start - 1
            if cp < 0:
                w("bndp = zero")
            else:
                for j in range(cp + 1):
                    if scratch:
                        w(f"pp_{j} = tl.load(scratch + {slot_of[cp] + j} * BK)")
                    else:
                        w(f"pp_{j} = cp{cp}_{j}")
                if scratch:
                    w(f"bndp = tl.load(scratch + {slot_of[cp] + cp + 1} * BK)")
                else:
                    w(f"bndp = bnd{cp}")
                if product:
                    # r_j = exp(G_cp - G_j) and A_cp, both as products of factors
                    for s in range(cp + 1):
                        w(f"ra_{s} = {_alpha(s, reload_checkpoints)}")
                    for j in range(cp - 1, -1, -1):
                        w(f"r_{j} = ra_{j + 1}" if j == cp - 1 else f"r_{j} = ra_{j + 1} * r_{j + 1}")
                    w("ap = ra_0")
                    for s in range(1, cp + 1):
                        w(f"ap = ap * ra_{s}")
                    ap = "ap"
            for t in range(seg_start, i):
                w(f"# rebuild P^({t}) from P^({t - 1})")
                lam_t = f"lam_{t}"
                if reload_checkpoints:
                    # Inhibit CSE across checkpoint reconstructions: retaining
                    # every earlier P intermediate costs more than these loads.
                    lam_t = f"rebuild_lam_{t}"
                    w(f"{lam_t} = tl.load(LAM + lbase + {t} * SL1, mask=key_mask, other=0.0, volatile=True).to(tl.float32)")
                w(f"retain_t = 1.0 - {lam_t}")
                if product:
                    w(f"ra_{t} = {_alpha(t, reload_checkpoints)}")
                    w(f"ap = ra_{t}" if ap is None else f"ap = ap * ra_{t}")
                    ap = "ap"
                    w(f"bndp = retain_t * bndp + {lam_t} * ap")
                    for j in range(t):
                        w(f"r_{j} = ra_{t}" if j == t - 1 else f"r_{j} = ra_{t} * r_{j}")
                    for j in range(t):
                        w(f"pp_{j} = retain_t * pp_{j} + {lam_t} * r_{j}")
                else:
                    w(f"bndp = retain_t * bndp + {lam_t} * tl.exp(G_{t})")
                    _relative(w, t, prefix="x")
                    for j in range(t):
                        w(f"pp_{j} = retain_t * pp_{j} + {lam_t} * x_{j}")
                w(f"pp_{t} = zero + {lam_t}")
            keep_prev = f"keep_{i - 1}"
        # current row: e_ij, P^{(i)}, Bnd^{(i)}
        if product:
            w(f"a_i = alpha_{i}" if ap is None else f"a_i = {ap} * alpha_{i}")
            for j in range(i):
                w(f"e_{j} = alpha_{i}" if j == i - 1 else f"e_{j} = alpha_{i} * r_{j}")
        else:
            _relative(w, i)
        for j in range(i):
            w(f"pi_{j} = retain * pp_{j} + lam_{i} * e_{j}")
        w(f"pi_{i} = zero + lam_{i}")
        w(f"bnd_i = retain * bndp + lam_{i} * a_i")
        # cotangents of P_j^{(i)}, Bnd_i, keep_i (+ tails / transport on the last row)
        tail = i == last
        if tail:
            for j in range(C):
                w(f"dt1_{j} = tl.load(DTAIL1 + vbase + {j} * K, mask=key_mask, other=0.0).to(tl.float32)")
                w(f"dt2_{j} = tl.load(DTAIL2 + vbase + {j} * K, mask=key_mask, other=0.0).to(tl.float32)")
            w("transport = (system * K + keys) * 4")
            w("dtr0 = tl.load(DTRANSPORT + transport + 0, mask=key_mask, other=0.0).to(tl.float32)")
            w("dtr1 = tl.load(DTRANSPORT + transport + 1, mask=key_mask, other=0.0).to(tl.float32)")
            w("dtr3 = tl.load(DTRANSPORT + transport + 3, mask=key_mask, other=0.0).to(tl.float32)")
        for j in range(i + 1):
            extra = f" + dt2_{j} * k_{j}" if tail else ""
            w(f"dp_{j} = dc_{j} * qs * k_{j}{extra}")
        carry = "" if tail else f"(1.0 - lam_{i + 1}) * "
        for j in range(i + 1):
            w(f"qp_{j} = dp_{j}" if tail else f"qp_{j} = dp_{j} + {carry}qp_{j}")
        w(f"dbnd_i = dq1_i * qs{' + dtr1' if tail else ''}")
        w(f"QB = dbnd_i" if tail else f"QB = dbnd_i + {carry}QB")
        w(f"dkeep_i = dq2_i * qs{' + dtr3' if tail else ''}")
        w(f"ql = dkeep_i" if tail else f"ql = dkeep_i + {carry}ql")
        # dlambda_i
        terms = [f"qp_{j} * (e_{j} - pp_{j})" for j in range(i)] + [f"qp_{i}", "QB * (a_i - bndp)"]
        w("dlam_vec = " + " + ".join(terms))
        w(f"tl.store(DLAM + base + {i} * H * K, dlam_vec - {keep_prev} * ql, mask=key_mask)")
        # decay cotangent
        for j in range(i):
            extra = f" + dt1_{j} * k_{j}" if tail else ""
            w(f"de_{j} = dc_{j} * qa * k_{j} + dm_{j} * er * k_{j} + lam_{i} * qp_{j}{extra}")
        w(f"dA = dabar_i * er + dq1_i * qa + lam_{i} * QB{' + dtr0' if tail else ''}")
        own = " + ".join([f"de_{j} * e_{j}" for j in range(i)] + ["dA * a_i"])
        w(f"dG_i = {own} - dgc_{i}")
        w("suffix = suffix + dG_i")
        w(f"tl.store(DG + base + {i} * H * K, suffix, mask=key_mask)")
        for j in range(i):
            w(f"dgc_{j} += de_{j} * e_{j}")
        # query, readout mix, erase gate, keys
        read = " + ".join([f"dc_{j} * k_{j} * (gm_i * e_{j} + (1.0 - gm_i) * pi_{j})" for j in range(i)]
                          + [f"dc_{i} * k_{i} * (gm_i + (1.0 - gm_i) * pi_{i})"])
        w(f"dq_i = dq1_i * (gm_i * a_i + (1.0 - gm_i) * bnd_i) + dq2_i * (1.0 - gm_i) * keep_{i} + {read}")
        mix = " + ".join([f"dc_{j} * k_{j} * (e_{j} - pi_{j})" for j in range(i)]
                         + [f"dc_{i} * k_{i} * (1.0 - pi_{i})"])
        w(f"dgm_i = q_i * (dq1_i * (a_i - bnd_i) - dq2_i * keep_{i} + {mix})")
        inter = " + ".join([f"dm_{j} * k_{j} * e_{j}" for j in range(i)]) or "zero"
        w(f"inter_k = dabar_i * a_i + {inter}")
        w("tl.store(DQ + base + %d * H * K, (dq_i * SCALE).to(DQ.dtype.element_ty), mask=key_mask)" % i)
        w("tl.store(DGAMMA + base + %d * H * K, dgm_i, mask=key_mask)" % i)
        w(f"tl.store(DB + base + {i} * H * K, (k_{i} * inter_k).to(DB.dtype.element_ty), mask=key_mask)")
        for j in range(i):
            extra = f" + dt1_{j} * e_{j} + dt2_{j} * pi_{j}" if tail else ""
            w(f"dk_{j} += dc_{j} * (qa * e_{j} + qs * pi_{j}) + dm_{j} * er * e_{j}{extra}")
        extra = f" + dt1_{i} + dt2_{i} * pi_{i}" if tail else ""
        w(f"dk_{i} += dc_{i} * (qa + qs * pi_{i}) + b_i * inter_k{extra}")
    w("# ---- key gradients ----")
    for j in range(C):
        w(f"tl.store(DK + base + {j} * H * K, dk_{j}.to(DK.dtype.element_ty), mask=key_mask)")
    return w.text()


FORWARD_COMMENT = """\
Readout row forward.  PRODUCT: every decay as a running product of the
per-step factors exp(g_t) (16 exponentials); otherwise as relative
exponentials exp(G_i - G_j) (136)."""

BACKWARD_COMMENT = """\
Readout row backward.  Default: P / Bnd checkpointed every CP=4 rows in
registers.  RELOAD: CP=8 with volatile lambda / decay reloads that keep each
checkpoint rebuild's live range private to its target row (K=128 on the GPUs
with a RELOAD_BWD table).  PRODUCT (with RELOAD): decays as running products of
the per-step factors, as the forward builds them.  ops/arch.py picks the flags."""


def generate(variants: bool = False) -> str:
    """The shipped kernels, one per direction with its implementations behind
    constexpr flags (gen_merge.merge_kernels); ``variants=True`` also emits
    other backward variants as separate kernels (``_cp8``: one checkpoint at
    row 7; ``_cp4s`` / ``_cp8s``: checkpoints in a per-program scratch slice).
    """
    forward = merge_kernels(
        "_readout_rows_fwd_kernel",
        {"product": generate_forward(), "exp": generate_forward(False)},
        {"product": {"PRODUCT": True}, "exp": {"PRODUCT": False}},
        FORWARD_COMMENT,
    )
    backward = merge_kernels(
        "_readout_rows_bwd_kernel",
        {"reload": generate_backward(8, reload_checkpoints=True),
         "cp4": generate_backward(4),
         "reload_product": generate_backward(8, reload_checkpoints=True, product=True)},
        {"reload": {"RELOAD": True, "PRODUCT": False},
         "cp4": {"RELOAD": False, "PRODUCT": False},
         "reload_product": {"RELOAD": True, "PRODUCT": True}},
        BACKWARD_COMMENT,
    )
    parts = [HEADER, forward, backward]
    if variants:
        parts.append(generate_backward(8, suffix="_cp8"))
        parts.append(generate_backward(4, scratch=True, suffix="_cp4s"))
        parts.append(generate_backward(8, scratch=True, suffix="_cp8s"))
    parts.append("ROWS_SCRATCH_SLOTS = {%s}\n" % ", ".join(
        f'"{name}": {sum(c + 2 for c in checkpoints(cp))}' for name, cp in (("_cp4s", 4), ("_cp8s", 8))))
    return "\n\n".join(parts)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(Path(__file__).with_name("readout_rows_triton.py")))
    ap.add_argument("--variants", action="store_true", help="also emit the A/B backward variants")
    args = ap.parse_args()
    text = generate(variants=args.variants)
    Path(args.out).write_text(text)
    print(f"wrote {args.out} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
